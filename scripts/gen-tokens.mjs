// Generates src/styles/tokens.css from design/system/tokens.json. Do not hand-edit the output.
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('../design/system/tokens.json', import.meta.url), 'utf8'));
const out = ['/* Generated by scripts/gen-tokens.mjs from design/system/tokens.json. Do not edit. */', ':root {'];
for (const c of t.color.tokens) out.push(`  --${c.name}: ${c.value};`);
for (const [k, stack] of Object.entries(t.type.families)) {
  const [first, ...rest] = stack.split(',').map((s) => s.trim());
  // next/font exposes the loaded face as --nf-<family>; fall back to the token's own name.
  out.push(`  --font-${k}: var(--nf-${k}, ${first})${rest.length ? ', ' + rest.join(', ') : ''};`);
}
for (const g of t.type.groups) for (const s of g.styles) {
  out.push(`  --${s.name}-family: var(--font-${g.family});`);
  out.push(`  --${s.name}-size: ${s.fontSize};`);
  out.push(`  --${s.name}-line: ${s.lineHeight};`);
  out.push(`  --${s.name}-weight: ${s.fontWeight};`);
  if (s.letterSpacing) out.push(`  --${s.name}-tracking: ${s.letterSpacing};`);
}
for (const group of ['spacing', 'radius', 'shadow', 'stroke']) for (const x of t[group].tokens) out.push(`  --${x.name}: ${x.value};`);
out.push('}');
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), out.join('\n') + '\n');
console.log('tokens.css written');
